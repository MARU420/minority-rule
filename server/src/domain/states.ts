/** Strict server-side match state machine. */
export type MatchState =
  | "WAITING_FOR_PLAYERS"
  | "QUESTION_SUBMISSION"
  | "PREPARING_MATCH"
  | "ROUND_INTRO"
  | "VOTING_OPEN"
  | "VOTING_LOCKED"
  | "ROUND_RESOLUTION"
  | "ROUND_RESULTS"
  | "MATCH_RESULTS"
  | "MATCH_COMPLETED"
  | "MATCH_CANCELLED";

const TRANSITIONS: Record<MatchState, MatchState[]> = {
  WAITING_FOR_PLAYERS: ["QUESTION_SUBMISSION", "MATCH_CANCELLED"],
  QUESTION_SUBMISSION: ["PREPARING_MATCH", "MATCH_CANCELLED"],
  PREPARING_MATCH: ["ROUND_INTRO", "MATCH_CANCELLED"],
  ROUND_INTRO: ["VOTING_OPEN", "MATCH_CANCELLED"],
  VOTING_OPEN: ["VOTING_LOCKED", "MATCH_CANCELLED"],
  VOTING_LOCKED: ["ROUND_RESOLUTION", "MATCH_CANCELLED"],
  ROUND_RESOLUTION: ["ROUND_RESULTS", "MATCH_CANCELLED"],
  ROUND_RESULTS: ["ROUND_INTRO", "MATCH_RESULTS", "MATCH_CANCELLED"],
  MATCH_RESULTS: ["MATCH_COMPLETED", "MATCH_CANCELLED"],
  MATCH_COMPLETED: [],
  MATCH_CANCELLED: [],
};

export function canTransition(from: MatchState, to: MatchState): boolean {
  return TRANSITIONS[from].includes(to);
}
